export function getGuides(category) {
  if (!category) return guides;
  return guides.filter(g => g.categorySlug === category);
}

export function getGuideBySlug(slug) {
  return guides.find(g => g.slug === slug) || null;
}

export function getFeaturedGuides() {
  return guides.slice(0, 4);
}

export function getRelatedGuides(guideId, categorySlug, limit = 3) {
  return guides
    .filter(g => g.id !== guideId && (!categorySlug || g.categorySlug === categorySlug))
    .slice(0, limit);
}
